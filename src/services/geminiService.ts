/**
 * AI Mentor Chat Assistant
 */
export async function sendMentorChatMessage(
  messages: ChatMessage[],
  currentRoadmap: RoadmapPathway | null,
  userProfile: UserProfile
): Promise<string> {
  const apiKey = getStoredApiKey();

  if (!apiKey) {
    const lastUserMsg = messages[messages.length - 1]?.text.toLowerCase() || '';
    if (lastUserMsg.includes('parent') || lastUserMsg.includes('explain')) {
      return "To explain this career to your parents, highlight the 5-10 year stability (+30% market growth), official degree options (B.Tech / B.Sc), and strong entry-level salary potential. You can also click 'Generate Parent Brief' above for a ready-to-print 1-page summary!";
    }
    if (lastUserMsg.includes('exam') || lastUserMsg.includes('jee') || lastUserMsg.includes('cuet')) {
      return "For entrance exam prep alongside your current schedule, dedicate 3 hours daily to core Math/Physics concepts, solve previous 5-year question papers, and take weekly mock tests on weekends.";
    }
    return `As your AI Career Mentor, I recommend focusing on building practical projects alongside your ${userProfile.streamOrField} studies. Is there a specific milestone in ${currentRoadmap ? currentRoadmap.title : 'your roadmap'} you would like to explore deeper?`;
  }

  const roadmapContext = currentRoadmap ? `Current Selected Roadmap: ${currentRoadmap.title}\nOverview: ${currentRoadmap.overview}\nMilestones: ${currentRoadmap.steps.map(s => s.phaseTitle).join(', ')}` : 'No specific roadmap selected yet.';

  const prompt = `
You are CAREERFORGE AI Mentor, an empathetic, expert career counselor for high schoolers, college students, and working professionals.
User Profile: Stage: ${userProfile.stage}, Stream: ${userProfile.streamOrField}.
${roadmapContext}

Chat History:
${messages.map(m => `${m.sender.toUpperCase()}: ${m.text}`).join('\n')}

Respond to the latest user message with clear, actionable, encouraging advice. Keep responses concise (2-4 paragraphs max). Use bullet points where appropriate.
`;

  try {
    return await callGeminiApi(prompt, apiKey);
  } catch (err) {
    return "I'm experiencing a brief connectivity hiccup with the AI server. However, based on your roadmap, focusing on your core milestone skills and entrance exams is your best next step!";
  }
}
